# ---------------------------------------------------------
# MAIN AGENT TRANSACTION
# ---------------------------------------------------------

@app.post(
    "/api/v1/agent/transact",
    response_model=TransactionResponse
)
def execute_agent_transaction(

    mandate: BuyerIntentMandate,

    product_id: str = Query(
        ...,
        description="Target product identifier"
    ),

    bid_unit_price_paise: int = Query(
        ...,
        description=(
            "Buyer offered unit price "
            "in integer paise"
        )
    ),

    db: Session = Depends(get_db)

):
    """
    Main policy-governed transaction flow.

    FLOW:

    1. Receive typed buyer mandate
    2. Check replay / duplicate request
    3. Validate product exists
    4. Request merchant quote
    5. Reserve inventory
    6. Validate quote using deterministic policy engine
    7. Create Razorpay TEST MODE order or MOCK order
    8. Consume reserved stock only after order creation
    9. Persist ledger and audit trail

    The merchant/agent layer never directly bypasses
    the deterministic policy engine.
    """


    # -----------------------------------------------------
    # STEP 1
    # MANDATE INGESTION AUDIT
    # -----------------------------------------------------

    AuditService.log_event(
        db=db,

        mandate_id=mandate.mandate_id,

        event_type="MANDATE_INGESTION",

        actor="BUYER_AGENT",

        status="INFO",

        payload={
            "user_id": mandate.user_id,
            "category": mandate.category,
            "max_budget_paise": mandate.max_budget_paise,
            "target_quantity": mandate.target_quantity,
            "allowed_merchants": mandate.allowed_merchants,
            "created_at": mandate.created_at,
            "expiry_seconds": mandate.expiry_seconds
        }
    )


    # -----------------------------------------------------
    # STEP 2
    # MANDATE EXPIRY PRE-CHECK
    # -----------------------------------------------------

    current_time = int(time.time())

    mandate_expiry = (
        mandate.created_at
        + mandate.expiry_seconds
    )

    if current_time > mandate_expiry:

        reason_code = "MANDATE_EXPIRED"

        message = (
            "The delegated purchase mandate has expired. "
            "No order or payment action was performed."
        )

        AuditService.log_event(
            db=db,

            mandate_id=mandate.mandate_id,

            event_type="MANDATE_REJECTED",

            actor="POLICY_ENGINE",

            status="BLOCKED",

            payload={
                "decision": "BLOCK",
                "reason_code": reason_code,
                "message": message,
                "mandate_expiry": mandate_expiry,
                "current_time": current_time
            }
        )

        raise HTTPException(
            status_code=400,

            detail={
                "decision": "BLOCK",
                "reason_code": reason_code,
                "message": message
            }
        )


    # -----------------------------------------------------
    # STEP 3
    # PRODUCT LOOKUP
    # -----------------------------------------------------

    product_record = (
        db.query(ProductInventory)
        .filter(
            ProductInventory.product_id
            == product_id
        )
        .first()
    )

    if not product_record:

        AuditService.log_event(
            db=db,

            mandate_id=mandate.mandate_id,

            event_type="CATALOG_LOOKUP_FAILED",

            actor="BUYER_AGENT",

            status="FAILED",

            payload={
                "product_id": product_id,
                "reason": "PRODUCT_NOT_FOUND"
            }
        )

        raise HTTPException(
            status_code=404,

            detail={
                "decision": "BLOCK",
                "reason_code": "PRODUCT_NOT_FOUND",
                "message": (
                    "Requested product does not exist "
                    "in merchant inventory."
                )
            }
        )


    # -----------------------------------------------------
    # STEP 4
    # REPLAY / DUPLICATE PROTECTION
    #
    # IMPORTANT:
    # Check BEFORE creating another stock reservation.
    # -----------------------------------------------------

    existing_tx = get_existing_transaction_for_request(
        db=db,

        mandate_id=mandate.mandate_id,

        product_id=product_id
    )

    if existing_tx:

        retail_total_paise = (
            product_record.retail_price_paise
            * existing_tx.quantity
        )

        savings_paise = max(
            0,

            retail_total_paise
            - existing_tx.total_amount_paise
        )

        AuditService.log_event(
            db=db,

            mandate_id=mandate.mandate_id,

            event_type="IDEMPOTENCY_HIT",

            actor="POLICY_ENGINE",

            status="INFO",

            payload={
                "message": (
                    "Duplicate transaction request "
                    "suppressed."
                ),

                "existing_order_id":
                    existing_tx.razorpay_order_id,

                "existing_status":
                    existing_tx.status,

                "idempotency_key":
                    existing_tx.idempotency_key
            },

            quote_id=existing_tx.quote_id
        )

        return TransactionResponse(

            status=(
                "REPLAY_SUPPRESSED_EXISTING_ORDER"
            ),

            decision="ALLOW",

            reason_code=(
                "IDEMPOTENT_CACHED_RESULT"
            ),

            razorpay_order_id=(
                existing_tx.razorpay_order_id
            ),

            amount_paise=(
                existing_tx.total_amount_paise
            ),

            negotiated_savings_paise=(
                savings_paise
            ),

            audit_trail={
                "idempotency_key":
                    existing_tx.idempotency_key,

                "quote_id":
                    existing_tx.quote_id,

                "is_replay": True,

                "original_transaction_status":
                    existing_tx.status
            }
        )


    # -----------------------------------------------------
    # STEP 5
    # MERCHANT QUOTE REQUEST
    #
    # Merchant performs deterministic negotiation and
    # reserves stock.
    # -----------------------------------------------------

    AuditService.log_event(
        db=db,

        mandate_id=mandate.mandate_id,

        event_type="QUOTE_REQUEST",

        actor="BUYER_AGENT",

        status="INFO",

        payload={
            "product_id": product_id,

            "requested_quantity":
                mandate.target_quantity,

            "offered_unit_price_paise":
                bid_unit_price_paise
        }
    )


    quote_data = merchant_agent.request_quote(

        db=db,

        mandate_id=mandate.mandate_id,

        product_id=product_id,

        requested_qty=(
            mandate.target_quantity
        ),

        offered_unit_price_paise=(
            bid_unit_price_paise
        )
    )


    # -----------------------------------------------------
    # STEP 6
    # MERCHANT REJECTION
    # -----------------------------------------------------

    if quote_data.get("status") == "REJECTED":

        reason = quote_data.get(
            "reason",
            "QUOTE_REJECTED"
        )

        AuditService.log_event(
            db=db,

            mandate_id=mandate.mandate_id,

            event_type="NEGOTIATION_FAILED",

            actor="MERCHANT_AGENT",

            status="FAILED",

            payload={
                "reason_code": reason,
                "product_id": product_id
            }
        )

        raise HTTPException(

            status_code=400,

            detail={
                "decision": "BLOCK",

                "reason_code": reason,

                "message": (
                    "Merchant rejected the quote "
                    "request. No payment action "
                    "was performed."
                )
            }
        )


    # -----------------------------------------------------
    # STEP 7
    # LOAD PERSISTED QUOTE
    # -----------------------------------------------------

    quote_id = quote_data["quote_id"]

    quote_record = (
        db.query(StockReservationQuote)
        .filter(
            StockReservationQuote.quote_id
            == quote_id
        )
        .first()
    )


    if not quote_record:

        AuditService.log_event(
            db=db,

            mandate_id=mandate.mandate_id,

            event_type="QUOTE_PERSISTENCE_FAILURE",

            actor="MERCHANT_AGENT",

            status="FAILED",

            payload={
                "quote_id": quote_id
            },

            quote_id=quote_id
        )

        raise HTTPException(

            status_code=500,

            detail={
                "decision": "BLOCK",

                "reason_code":
                    "QUOTE_NOT_PERSISTED",

                "message": (
                    "Quote could not be safely "
                    "loaded from persistent storage. "
                    "No payment was attempted."
                )
            }
        )


    # -----------------------------------------------------
    # STEP 8
    # EXPIRED QUOTE CHECK + INVENTORY RELEASE
    # -----------------------------------------------------

    if release_expired_quote_if_needed(
        db,
        quote_record
    ):

        AuditService.log_event(
            db=db,

            mandate_id=mandate.mandate_id,

            event_type="QUOTE_EXPIRED",

            actor="POLICY_ENGINE",

            status="BLOCKED",

            payload={
                "quote_id": quote_id,

                "message": (
                    "Quote expired before payment "
                    "authorization. Reserved stock "
                    "was released."
                )
            },

            quote_id=quote_id
        )

        raise HTTPException(

            status_code=400,

            detail={
                "decision": "BLOCK",

                "reason_code":
                    "QUOTE_EXPIRED",

                "message": (
                    "Quote expired and reserved "
                    "inventory was released. "
                    "No payment was attempted."
                )
            }
        )


    # -----------------------------------------------------
    # STEP 9
    # CANONICAL SHA-256 IDEMPOTENCY KEY
    # -----------------------------------------------------

    idempotency_key = (
        DeterministicPolicyEngine
        .generate_idempotency_key(

            mandate_id=mandate.mandate_id,

            merchant_id=(
                quote_record.merchant_id
            ),

            quote_id=quote_id,

            total_paise=(
                quote_record.total_amount_paise
            )
        )
    )


    # -----------------------------------------------------
    # STEP 10
    # DATABASE IDEMPOTENCY CHECK
    # -----------------------------------------------------

    existing_idempotent_tx = (
        AuditService
        .get_existing_transaction_by_idempotency(
            db,
            idempotency_key
        )
    )

    if existing_idempotent_tx:

        # Release current quote if this request somehow
        # created an additional reservation.

        MerchantSalesAgent.release_reservation(
            db,

            quote_id,

            reason="REPLAY_DUPLICATE"
        )

        AuditService.log_event(
            db=db,

            mandate_id=mandate.mandate_id,

            event_type="IDEMPOTENCY_HIT",

            actor="POLICY_ENGINE",

            status="INFO",

            payload={
                "message": (
                    "Canonical idempotency key "
                    "already exists."
                ),

                "idempotency_key":
                    idempotency_key,

                "existing_order_id":
                    existing_idempotent_tx
                    .razorpay_order_id
            },

            quote_id=quote_id
        )

        return TransactionResponse(

            status=(
                "REPLAY_SUPPRESSED_EXISTING_ORDER"
            ),

            decision="ALLOW",

            reason_code=(
                "IDEMPOTENT_CACHED_RESULT"
            ),

            razorpay_order_id=(
                existing_idempotent_tx
                .razorpay_order_id
            ),

            amount_paise=(
                existing_idempotent_tx
                .total_amount_paise
            ),

            negotiated_savings_paise=max(
                0,

                (
                    product_record
                    .retail_price_paise
                    * existing_idempotent_tx.quantity
                )

                -

                existing_idempotent_tx
                .total_amount_paise
            ),

            audit_trail={
                "idempotency_key":
                    idempotency_key,

                "is_replay": True
            }
        )


    # -----------------------------------------------------
    # STEP 11
    # DETERMINISTIC PAYMENT TRUST ENGINE
    #
    # This is the final policy authority.
    # -----------------------------------------------------

    decision, reason_code, message = (
        DeterministicPolicyEngine
        .validate_transaction(

            mandate=mandate,

            product=product_record,

            quote=quote_record
        )
    )


    # -----------------------------------------------------
    # STEP 12
    # POLICY BLOCK
    # -----------------------------------------------------

    if decision != "ALLOW":

        MerchantSalesAgent.release_reservation(

            db,

            quote_id,

            reason=reason_code
        )


        AuditService.log_event(

            db=db,

            mandate_id=mandate.mandate_id,

            event_type=(
                "GUARDRAIL_INTERCEPTION"
            ),

            actor="POLICY_ENGINE",

            status="BLOCKED",

            payload={

                "decision": decision,

                "reason_code":
                    reason_code,

                "message":
                    message,

                "attempted_total_paise":
                    quote_record
                    .total_amount_paise

            },

            quote_id=quote_id
        )


        # Store blocked attempt if possible.
        # The ledger remains useful for red-team
        # evidence and recovery auditing.

        try:

            AuditService.create_transaction_record(

                db=db,

                mandate_id=(
                    mandate.mandate_id
                ),

                idempotency_key=(
                    idempotency_key
                ),

                merchant_id=(
                    quote_record
                    .merchant_id
                ),

                product_id=product_id,

                quote_id=quote_id,

                quantity=(
                    quote_record.quantity
                ),

                unit_price_paise=(
                    quote_record
                    .unit_price_paise
                ),

                total_amount_paise=(
                    quote_record
                    .total_amount_paise
                ),

                status=(
                    f"GUARDRAIL_"
                    f"{reason_code}"
                )
            )

        except IntegrityError:

            db.rollback()


        raise HTTPException(

            status_code=400,

            detail={

                "decision":
                    decision,

                "reason_code":
                    reason_code,

                "message":
                    message
            }
        )


    # -----------------------------------------------------
    # STEP 13
    # POLICY ALLOW
    # -----------------------------------------------------

    AuditService.log_event(

        db=db,

        mandate_id=mandate.mandate_id,

        event_type="POLICY_VALIDATION",

        actor="POLICY_ENGINE",

        status="SUCCESS",

        payload={

            "decision":
                "ALLOW",

            "reason_code":
                reason_code,

            "checks_passed":[

                "MANDATE_EXPIRY",

                "MERCHANT_ALLOWLIST",

                "CATEGORY_SCOPE",

                "QUOTE_EXPIRY",

                "QUOTE_STATUS",

                "BUDGET_CAP",

                "QUANTITY_CAP",

                "SANITY_VALUES"

            ],

            "total_amount_paise":
                quote_record
                .total_amount_paise
        },

        quote_id=quote_id
    )


    # -----------------------------------------------------
    # STEP 14
    # CREATE PAYMENT ORDER
    #
    # Razorpay TEST MODE if credentials exist.
    #
    # MOCK/DEMO fallback if placeholder keys are used.
    # -----------------------------------------------------

    try:

        order = (
            payment_service
            .create_gated_order(

                amount_paise=(
                    quote_record
                    .total_amount_paise
                ),

                receipt_id=(
                    f"rcpt_"
                    f"{mandate.mandate_id[:10]}"
                ),

                notes={

                    "mandate_id":
                        mandate.mandate_id,

                    "quote_id":
                        quote_id,

                    "product_id":
                        product_id,

                    "buyer_id":
                        mandate.user_id

                },

                idempotency_key=(
                    idempotency_key
                )
            )
        )


    except Exception as payment_error:

        # -------------------------------------------------
        # PAYMENT FAILURE RECOVERY
        #
        # Important:
        # Release stock.
        # Do NOT consume inventory.
        # Do NOT mark payment/order as successful.
        # -------------------------------------------------

        MerchantSalesAgent.release_reservation(

            db,

            quote_id,

            reason="PAYMENT_ORDER_FAILED"
        )


        AuditService.log_event(

            db=db,

            mandate_id=mandate.mandate_id,

            event_type=(
                "PAYMENT_ORDER_FAILED"
            ),

            actor="RAZORPAY_GATEWAY",

            status="FAILED",

            payload={

                "quote_id":
                    quote_id,

                "error":
                    str(payment_error),

                "recovery":
                    "STOCK_RELEASED"

            },

            quote_id=quote_id
        )


        raise HTTPException(

            status_code=502,

            detail={

                "decision":
                    "BLOCK",

                "reason_code":
                    "PAYMENT_ORDER_CREATION_FAILED",

                "message": (
                    "Payment order creation failed. "
                    "Reserved stock was released. "
                    "No successful payment is claimed."
                )
            }
        )


    # -----------------------------------------------------
    # STEP 15
    # DETERMINE MODE
    # -----------------------------------------------------

    mock_mode = is_mock_order(order)


    if mock_mode:

        transaction_status = (
            "ORDER_CREATED_MOCK_MODE"
        )

        gateway_event = (
            "MOCK_ORDER_CREATED"
        )

        gateway_actor = (
            "MOCK_GATEWAY"
        )

    else:

        transaction_status = (
            "ORDER_CREATED_TEST_MODE"
        )

        gateway_event = (
            "RAZORPAY_TEST_ORDER_CREATED"
        )

        gateway_actor = (
            "RAZORPAY_GATEWAY"
        )


    # -----------------------------------------------------
    # STEP 16
    # CONSUME STOCK RESERVATION
    #
    # This happens after successful ORDER creation.
    #
    # IMPORTANT:
    # Creating an order is not the same as
    # payment settlement.
    # -----------------------------------------------------

    consumed = (
        MerchantSalesAgent
        .consume_reservation(

            db,

            quote_id
        )
    )


    if not consumed:

        AuditService.log_event(

            db=db,

            mandate_id=mandate.mandate_id,

            event_type=(
                "STOCK_CONSUMPTION_FAILURE"
            ),

            actor="POLICY_ENGINE",

            status="FAILED",

            payload={

                "quote_id":
                    quote_id,

                "order_id":
                    order.get("id"),

                "message": (
                    "Order was created but inventory "
                    "reservation could not be safely "
                    "consumed."
                )

            },

            quote_id=quote_id
        )


        raise HTTPException(

            status_code=500,

            detail={

                "decision":
                    "BLOCK",

                "reason_code":
                    "POST_ORDER_INVENTORY_FAILURE",

                "message": (
                    "Order was created but inventory "
                    "state requires recovery. "
                    "Check audit trail."
                )
            }
        )


    # -----------------------------------------------------
    # STEP 17
    # CREATE TRANSACTION LEDGER RECORD
    # -----------------------------------------------------

    try:

        transaction_record = (
            AuditService
            .create_transaction_record(

                db=db,

                mandate_id=(
                    mandate.mandate_id
                ),

                idempotency_key=(
                    idempotency_key
                ),

                merchant_id=(
                    quote_record
                    .merchant_id
                ),

                product_id=product_id,

                quote_id=quote_id,

                quantity=(
                    quote_record.quantity
                ),

                unit_price_paise=(
                    quote_record
                    .unit_price_paise
                ),

                total_amount_paise=(
                    quote_record
                    .total_amount_paise
                ),

                status=(
                    transaction_status
                ),

                razorpay_order_id=(
                    order.get("id")
                )
            )
        )


    except IntegrityError:

        # Database uniqueness is the final safety
        # boundary for duplicate idempotency keys.

        db.rollback()


        existing_transaction = (

            AuditService
            .get_existing_transaction_by_idempotency(

                db,

                idempotency_key
            )
        )


        if existing_transaction:

            return TransactionResponse(

                status=(
                    "REPLAY_SUPPRESSED_EXISTING_ORDER"
                ),

                decision="ALLOW",

                reason_code=(
                    "IDEMPOTENT_CACHED_RESULT"
                ),

                razorpay_order_id=(
                    existing_transaction
                    .razorpay_order_id
                ),

                amount_paise=(
                    existing_transaction
                    .total_amount_paise
                ),

                negotiated_savings_paise=max(

                    0,

                    (
                        product_record
                        .retail_price_paise
                        * existing_transaction.quantity
                    )

                    -

                    existing_transaction
                    .total_amount_paise
                ),

                audit_trail={

                    "idempotency_key":
                        idempotency_key,

                    "is_replay":
                        True
                }
            )


        raise


    # -----------------------------------------------------
    # STEP 18
    # FINAL PAYMENT / ORDER AUDIT EVENT
    # -----------------------------------------------------

    AuditService.log_event(

        db=db,

        mandate_id=mandate.mandate_id,

        event_type=gateway_event,

        actor=gateway_actor,

        status="SUCCESS",

        payload={

            "order_id":
                order.get("id"),

            "amount_paise":
                quote_record
                .total_amount_paise,

            "mode":

                (
                    "MOCK_DEMO"
                    if mock_mode
                    else "RAZORPAY_TEST_MODE"
                ),

            "important_note":

                (
                    "Order creation does not "
                    "represent confirmed payment "
                    "settlement."
                ),

            "idempotency_key":
                idempotency_key

        },

        quote_id=quote_id
    )


    # -----------------------------------------------------
    # STEP 19
    # CALCULATE SAVINGS
    # -----------------------------------------------------

    retail_total_paise = (

        product_record
        .retail_price_paise

        *

        quote_record.quantity
    )


    savings_paise = max(

        0,

        retail_total_paise

        -

        quote_record
        .total_amount_paise
    )


    # -----------------------------------------------------
    # STEP 20
    # SUCCESS RESPONSE
    # -----------------------------------------------------

    return TransactionResponse(

        status=transaction_status,

        decision="ALLOW",

        reason_code=(
            "PASSED_ALL_GUARDRAILS"
        ),

        razorpay_order_id=(
            order.get("id")
        ),

        amount_paise=(
            quote_record
            .total_amount_paise
        ),

        negotiated_savings_paise=(
            savings_paise
        ),
        cross_sell_offer=quote_data.get(
             "cross_sell_offer"
        ),

        audit_trail={

            "mandate_id":
                mandate.mandate_id,

            "quote_id":
                quote_id,

            "idempotency_key":
                idempotency_key,

            "payment_mode":

                (
                    "MOCK_DEMO"
                    if mock_mode
                    else "RAZORPAY_TEST_MODE"
                ),

            "payment_state":

                (
                    "ORDER_CREATED_NOT_SETTLED"
                ),

            "guardrail_status":
                "PASSED"
        }
    )


