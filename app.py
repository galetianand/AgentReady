def is_mock_order(order: dict) -> bool:
    """
    Determines whether the returned order was generated by
    the clearly labelled local MOCK/DEMO fallback.
    """

    order_id = str(order.get("id", ""))

    return (
        order_id.startswith("order_mock_")
        or order_id.startswith("order_sim_")
    )


def get_existing_transaction_for_request(
    db: Session,
    mandate_id: str,
    product_id: str
):
    """
    Replay protection before creating another quote reservation.

    This prevents a repeated request for the same mandate/product
    from creating another order after an earlier successful order
    already exists.

    The canonical idempotency key remains stored in the ledger.
    """

    return (
        db.query(TransactionLedger)
        .filter(
            TransactionLedger.mandate_id == mandate_id,
            TransactionLedger.product_id == product_id,
            TransactionLedger.status.in_(
                [
                    "ORDER_CREATED_TEST_MODE",
                    "ORDER_CREATED_MOCK_MODE"
                ]
            )
        )
        .order_by(TransactionLedger.created_at.asc())
        .first()
    )


def release_expired_quote_if_needed(
    db: Session,
    quote: StockReservationQuote
):
    """
    Releases inventory if the quote has expired before payment.
    """

    now = int(time.time())

    if (
        quote
        and quote.status == "RESERVED"
        and now > quote.expires_at
    ):
        MerchantSalesAgent.release_reservation(
            db,
            quote.quote_id,
            reason="EXPIRED"
        )

        return True

    return False


