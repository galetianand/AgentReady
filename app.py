# RAZORPAY WEBHOOK - PAYMENT SETTLEMENT RECONCILIATION
# =============================================================

@app.post("/api/v1/webhooks/razorpay")
async def razorpay_webhook_handler(
    request: Request,
    x_razorpay_signature: Optional[str] = Header(None),
    db: Session = Depends(get_db)
):
    """
    Receives Razorpay webhook events and reconciles
    payment settlement with the local transaction ledger.
    """

    # ---------------------------------------------------------
    # 1. CHECK SIGNATURE HEADER
    # ---------------------------------------------------------

    if not x_razorpay_signature:
        raise HTTPException(
            status_code=400,
            detail="Missing Razorpay signature"
        )

    # ---------------------------------------------------------
    # 2. READ RAW REQUEST BODY
    # ---------------------------------------------------------

    raw_body = await request.body()

    # ---------------------------------------------------------
    # 3. VERIFY WEBHOOK SIGNATURE
    # ---------------------------------------------------------

    if not payment_service.verify_webhook_signature(
        raw_body,
        x_razorpay_signature
    ):
        raise HTTPException(
            status_code=400,
            detail="Invalid webhook signature"
        )

    # ---------------------------------------------------------
    # 4. PARSE VERIFIED WEBHOOK PAYLOAD
    # ---------------------------------------------------------

    payload = await request.json()
    event_type = payload.get("event")

    # ---------------------------------------------------------
    # 5. PROCESS SUCCESSFUL ORDER PAYMENT
    # ---------------------------------------------------------

    if event_type == "order.paid":

        try:

            order_entity = (
                payload
                .get("payload", {})
                .get("order", {})
                .get("entity", {})
            )

            razorpay_order_id = order_entity.get("id")

            if not razorpay_order_id:
                raise HTTPException(
                    status_code=400,
                    detail="Missing Razorpay order ID"
                )

            # -------------------------------------------------
            # FIND TRANSACTION IN LOCAL LEDGER
            # -------------------------------------------------

            tx = (
                db.query(TransactionLedger)
                .filter(
                    TransactionLedger.razorpay_order_id
                    == razorpay_order_id
                )
                .first()
            )

            # -------------------------------------------------
            # UPDATE TRANSACTION TO SETTLED
            # -------------------------------------------------

            if tx:

                # Prevent duplicate webhook processing
                if tx.status != "SETTLED":

                    tx.status = "SETTLED"

                    db.commit()

                    # -----------------------------------------
                    # AUDIT EVENT
                    # -----------------------------------------

                    AuditService.log_event(
                        db=db,
                        mandate_id=tx.mandate_id,
                        event_type="PAYMENT_SETTLED_WEBHOOK",
                        actor="RAZORPAY_GATEWAY",
                        status="SUCCESS",
                        payload={
                            "message": (
                                "Verified Razorpay webhook "
                                "signature and reconciled "
                                "transaction settlement"
                            ),
                            "razorpay_order_id": (
                                razorpay_order_id
                            )
                        },
                        quote_id=tx.quote_id
                    )

        except HTTPException:
            raise

        except Exception as error:

            db.rollback()

            raise HTTPException(
                status_code=500,
                detail=(
                    "Webhook processing failed: "
                    + str(error)
                )
            )

    # ---------------------------------------------------------
    # 6. ACKNOWLEDGE WEBHOOK
    # ---------------------------------------------------------

    return {
        "status": "ok",
        "event": event_type
    }