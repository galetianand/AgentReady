@app.get(
    "/api/v1/audit/{mandate_id}",
    response_model=AuditLedgerResponse
)
def get_audit_trail(

    mandate_id: str,

    db: Session = Depends(get_db)

):
    """
    Returns chronological audit telemetry
    for the specified mandate.
    """

    events = (

        db.query(AuditEventLog)

        .filter(
            AuditEventLog.mandate_id
            == mandate_id
        )

        .order_by(
            AuditEventLog.timestamp.asc()
        )

        .all()
    )


    transaction = (

        db.query(TransactionLedger)

        .filter(
            TransactionLedger.mandate_id
            == mandate_id
        )

        .order_by(
            TransactionLedger.created_at.desc()
        )

        .first()
    )


    timeline = []


    for event in events:

        try:

            details = json.loads(
                event.payload
            )

        except Exception:

            details = {
                "raw_payload":
                    event.payload
            }


        timeline.append({

            "timestamp":
                event.timestamp,

            "actor":
                event.actor,

            "event_type":
                event.event_type,

            "status":
                event.status,

            "details":
                details
        })


    return AuditLedgerResponse(

        mandate_id=mandate_id,

        transaction_status=(

            transaction.status

            if transaction

            else "NOT_FOUND"
        ),

        total_events=len(timeline),

        timeline=timeline
    )

